/**
 * Regenerates lib/whatsapp/countries.ts and public/flags/*.webp.
 *
 *   npm i -D flag-icons && node scripts/generate-country-data.mjs
 *
 * Both are build artifacts kept in git so the app needs no network at runtime.
 * Run this after upgrading libphonenumber-js, which is the only authority on
 * calling codes here: hand-editing a code back into "1809" is the bug this
 * whole file exists to prevent.
 */
import { getCountries, getCountryCallingCode } from "libphonenumber-js";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const FLAG_SOURCE = "node_modules/flag-icons/flags/4x3/";
const FLAG_OUTPUT = "public/flags/";
const TABLE = "lib/whatsapp/countries.ts";

/**
 * Every +1 territory except the United States and Canada is identified by its
 * area code, which belongs to the national number. Listing them lets the
 * picker answer a search for "809" and lets a typed number pick its own flag.
 */
const AREA_CODES = {
  AG: ["268"], AI: ["264"], AS: ["684"], BB: ["246"], BM: ["441"],
  BS: ["242"], DM: ["767"], DO: ["809", "829", "849"], GD: ["473"],
  GU: ["671"], JM: ["876", "658"], KN: ["869"], KY: ["345"], LC: ["758"],
  MP: ["670"], MS: ["664"], PR: ["787", "939"], SX: ["721"], TC: ["649"],
  TT: ["868"], VC: ["784"], VG: ["284"], VI: ["340"],
};

// Spanish names are ours; libphonenumber ships none. Reused from the existing
// table so a rerun never renames a country behind the operator's back.
const NAMES = Object.fromEntries(
  [...readFileSync(TABLE, "utf8").matchAll(/\["([A-Z]{2})", "([^"]+)"/g)].map(
    (match) => [match[1], match[2]],
  ),
);

const collator = new Intl.Collator("es");
const rows = getCountries()
  .map((iso) => ({
    iso,
    name: NAMES[iso],
    dial: getCountryCallingCode(iso),
    areaCodes: AREA_CODES[iso],
  }))
  .sort((a, b) => collator.compare(a.name ?? a.iso, b.name ?? b.iso));

const unnamed = rows.filter((row) => !row.name);
if (unnamed.length > 0) {
  throw new Error(
    `Sin nombre en español: ${unnamed.map((r) => r.iso).join(" ")}. ` +
      `Agrégalos a ${TABLE} antes de regenerar.`,
  );
}

// The United States leads because it is the main market.
const ordered = [
  rows.find((row) => row.iso === "US"),
  ...rows.filter((row) => row.iso !== "US"),
];

const body = ordered
  .map(({ iso, name, dial, areaCodes }) => {
    const area = areaCodes ? `, ["${areaCodes.join('","')}"]` : "";
    return `  ["${iso}", "${name}", "${dial}"${area}],`;
  })
  .join("\n");

writeFileSync(
  TABLE,
  `import type { CountryCode } from "libphonenumber-js";

export interface Country {
  iso: CountryCode;
  name: string;
  /** The real calling code. Every +1 territory carries "1", never "1809". */
  dial: string;
  /**
   * North American area codes belonging to this territory. They are part of
   * the national number, not of the calling code; they are kept only so the
   * picker can be searched by them and so a typed number can pick its flag.
   */
  areaCodes?: readonly string[];
}

/**
 * Generated by scripts/generate-country-data.mjs from libphonenumber's own
 * metadata, so a calling code can never drift from what the parser believes.
 * Names are ours, in Spanish. Do not edit by hand.
 */
const RAW: ReadonlyArray<
  readonly [string, string, string, ReadonlyArray<string>?]
> = [
${body}
];

export const COUNTRY_CODES: ReadonlyArray<Country> = RAW.map(
  ([iso, name, dial, areaCodes]) => ({
    iso: iso as CountryCode,
    name,
    dial,
    ...(areaCodes ? { areaCodes } : {}),
  }),
);
`,
  "utf8",
);

// 72x54 is three times the 24x18 the picker draws, so it stays sharp on a
// retina screen while every flag lands under two kilobytes.
mkdirSync(FLAG_OUTPUT, { recursive: true });
const withoutFlag = [];
for (const { iso } of ordered) {
  const source = `${FLAG_SOURCE}${iso.toLowerCase()}.svg`;
  if (!existsSync(source)) {
    withoutFlag.push(iso);
    continue;
  }
  await sharp(source, { density: 200 })
    .resize(72, 54, { fit: "fill" })
    .webp({ quality: 90, effort: 6 })
    .toFile(`${FLAG_OUTPUT}${iso.toLowerCase()}.webp`);
}

console.log(`países: ${ordered.length}`);
console.log(`banderas: ${ordered.length - withoutFlag.length}`);
console.log(
  `sin bandera (caen a su código ISO): ${withoutFlag.join(" ") || "ninguna"}`,
);
